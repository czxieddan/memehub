"""Generate public dependency evidence from locked Cargo metadata, without builds."""
from __future__ import annotations
import argparse
import json
import shutil
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REVISION = "018eaa0fbe8caf779ee6c90c8343c97da8b281e5"


def license_files(package: dict) -> list[Path]:
    directory = Path(package["manifest_path"]).parent
    files = set()
    for pattern in ("LICENSE*", "LICENCE*", "COPYING*", "NOTICE*", "AUTHORS*", "UNLICENSE*"):
        files.update(path for path in directory.glob(pattern) if path.is_file())
    if package.get("license_file"):
        files.add(directory / package["license_file"])
    retained = ROOT / ".ahcl/THIRD-PARTY-LICENSES" / f'{package["name"]}-{package["version"]}'
    return sorted(files) or sorted(path for path in retained.glob("*") if path.is_file())


def copy_licenses(package: dict) -> list[str]:
    destination = ROOT / ".ahcl/THIRD-PARTY-LICENSES" / f'{package["name"]}-{package["version"]}'
    paths = license_files(package)
    if not paths:
        raise ValueError(f'no license evidence found for {package["name"]} {package["version"]}')
    destination.mkdir(parents=True, exist_ok=True)
    links = []
    for source in paths:
        target = destination / source.name
        if source.resolve() != target.resolve():
            shutil.copyfile(source, target)
        links.append(f'[{source.name}]({target.relative_to(ROOT / ".ahcl").as_posix()})')
    return links


def package_row(package: dict, checksums: dict, direct: set[str]) -> str:
    name, version = package["name"], package["version"]
    source = package.get("source") or "workspace"
    authors = "; ".join(package.get("authors", [])) or "Copyright holders identified in license copies"
    license_name = package.get("license") or "LicenseRef-AHCL-1.2"
    upstream = package.get("repository") or package.get("homepage") or f'https://crates.io/crates/{name}/{version}'
    if source.startswith("git+"):
        links = "[upstream license](../licenses/RNovModularDB/LICENSE), [materials](../licenses/RNovModularDB/.ahcl/AHCL-DEPENDENCIES.md)"
        digest = REVISION
        acquisition = f"Cargo Git dependency at {REVISION}"
    else:
        links = ", ".join(copy_licenses(package))
        digest = checksums[(name, version)]
        acquisition = f"Cargo registry: https://crates.io/api/v1/crates/{name}/{version}/download"
    level = "direct" if name in direct else "transitive"
    columns = [f"{name} {version}", authors, f"Rust dependency ({level}); see Cargo metadata graph", upstream, acquisition, digest, license_name, links]
    return "| " + " | ".join(str(value).replace("|", "\\|").replace("\n", " ") for value in columns) + " |"


def generate(metadata_path: Path) -> None:
    metadata = json.loads(metadata_path.read_text(encoding="utf-8"))
    lock = tomllib.loads((ROOT / "Cargo.lock").read_text(encoding="utf-8"))
    checksums = {(item["name"], item["version"]): item.get("checksum", REVISION) for item in lock["package"]}
    members = set(metadata["workspace_members"])
    workspace = [package for package in metadata["packages"] if package["id"] in members]
    direct = {dependency["name"] for package in workspace for dependency in package["dependencies"]}
    external = sorted((package for package in metadata["packages"] if package["id"] not in members), key=lambda item: (item["name"], item["version"]))
    lines = ["# Dependencies and Referenced Materials", "", "Generated by `tools/license_inventory.py --metadata <cargo-metadata.json>` from `cargo metadata --locked --format-version 1`. The table includes all resolved target, build and test dependencies. Registry digests are SHA-256; Git dependencies use commit IDs. Package-declared authors and verbatim license copies identify rights holders. Actual target selection follows Cargo.lock and Cargo's dependency graph.", "", "The five business crates and root executable are memehub components owned by czxieddan under the root AHCL notice. All external Rust packages are listed below; third-party licenses remain their own.", "", "| Package | Rights holders | Purpose / relationship | Upstream | Acquisition | Digest / commit | License | Verbatim copy |", "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    lines.extend(package_row(package, checksums, direct) for package in external)
    lines.extend(["", "## Build, deployment and remote services", "", "See [tool and service evidence](../docs/dependencies.md) for Rust, Python, Git, Docker, the base images, GitHub API and workflow actions. Exact GitHub Action revisions are pinned in the template workflows. No third-party images, icons, web fonts or JavaScript libraries are used by the embedded frontend.", ""])
    (ROOT / ".ahcl/AHCL-DEPENDENCIES.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"Indexed {len(external)} packages and their license materials")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--metadata", type=Path, required=True)
    generate(parser.parse_args().metadata)
